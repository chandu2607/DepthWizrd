"""Render EXPERIMENT_RESULTS.md from a run's measured metrics.

Every number here comes from the actual run passed in `results`; nothing is
hard-coded. If a metric is missing (baseline skipped, no valid pixels) it prints
'n/a' rather than a fabricated value. When the run is not valid evidence
(synthetic / fake-depth), a prominent warning banner is emitted.
"""
from __future__ import annotations

from pathlib import Path

BASELINE_ORDER = ["A_raw_depth", "B_global_affine", "C_learned_fusion",
                  "D_rdah_net", "oracle_affine_upper_bound"]
NICE = {
    "A_raw_depth": "A · raw depth (scale-free)",
    "B_global_affine": "B · global affine",
    "C_learned_fusion": "C · learned fusion (hypothesis)",
    "D_rdah_net": "D · RDAH-Net (reference)",
    "oracle_affine_upper_bound": "oracle affine (upper bound)",
}


def _f(x, nd=2):
    if x is None or (isinstance(x, float) and x != x):
        return "n/a"
    return f"{x:.{nd}f}"


def _agg_row(name, ev, kind, note=""):
    agg = (ev or {}).get("aggregate", {}).get(kind, {}) if ev else {}
    metric_ok = (ev or {}).get("metric_valid", True)
    mae = _f(agg.get("mae_pooled")) if metric_ok else "—*"
    rmse = _f(agg.get("rmse_pooled")) if metric_ok else "—*"
    r = _f(agg.get("pearson_mean"))
    n = agg.get("n_scenes", "n/a")
    return f"| {NICE.get(name, name)} | {mae} | {rmse} | {r} | {n} |{note}"


def _table(group, kind, names):
    lines = ["| method | MAE (m) | RMSE (m) | Pearson r | scenes |",
             "|---|---|---|---|---|"]
    for nm in names:
        if nm in group:
            lines.append(_agg_row(nm, group[nm], kind))
    return "\n".join(lines)


def render(results: dict) -> str:
    meta = results.get("meta", {})
    dec = results.get("decision", {})
    evidence_valid = meta.get("evidence_valid", False)
    idn = results.get("indomain", {})
    xc = results.get("xcity", {})
    names = [n for n in BASELINE_ORDER if n in idn or n in xc]

    out: list[str] = []
    out.append("# DepthWizard — Phase-1 Feasibility Results\n")
    out.append("_This file is generated by `scripts/run_phase1.py`. Every number "
               "below is measured by that run; placeholders read `n/a`._\n")

    if not evidence_valid:
        out.append("> # ⚠️ NOT VALID FEASIBILITY EVIDENCE\n"
                   "> This run used **synthetic** data and/or **fake depth** "
                   "(`--allow-fake-depth`). The numbers below only prove the code "
                   "executes end-to-end. Re-run on **real DFC2019** with the real "
                   "Depth Anything V2 prior and a **city-held-out** split before "
                   "using any number to decide GO/MODIFY/ABANDON.\n")

    # ---- run metadata ----
    out.append("## Run metadata\n")
    out.append(f"- data source: `{meta.get('source')}`  |  evidence valid: "
               f"**{evidence_valid}**")
    out.append(f"- depth prior: `{meta.get('depth_model')}`"
               + ("  **(FAKE — offline stub)**" if meta.get("fake_depth") else ""))
    out.append(f"- device: `{meta.get('device')}`  |  torch: {meta.get('has_torch')}")
    out.append(f"- train cities: `{meta.get('train_cities')}`  |  "
               f"in-domain val city: `{meta.get('val_cities')}`  |  "
               f"**held-out test city: `{meta.get('test_cities')}`**")
    out.append(f"- tiles: train={meta.get('n_train')}, val={meta.get('n_val')}, "
               f"test={meta.get('n_test')}  |  tile_size={meta.get('tile_size')}")
    out.append(f"- seeds (head): `{meta.get('seeds')}`  |  head params: "
               f"{meta.get('head_params', 'n/a')}\n")

    # ---- headline: cross-city ----
    out.append("## Cross-city generalization (held-out TEST city) — headline\n")
    out.append("_The number that matters. Trained on the train city, evaluated on a "
               "city never seen in training. All-pixel metrics:_\n")
    out.append(_table(xc, "all", names))
    out.append("\n### Cross-city — buildings only\n")
    out.append(_table(xc, "building", names))
    out.append("\n### Cross-city — non-building only\n")
    out.append(_table(xc, "non_building", names))
    out.append("\n`—*` = MAE/RMSE omitted for the scale-free raw-depth baseline "
               "(only Pearson r is meaningful there).\n")

    # ---- in-domain ----
    out.append("## In-domain (held-out tiles from the TRAIN city)\n")
    out.append(_table(idn, "all", names))
    out.append("")

    # ---- reproducibility ----
    rep = results.get("reproducibility", {})
    if rep:
        out.append("## Reproducibility (learned head across seeds)\n")
        out.append(f"- cross-city MAE across seeds {rep.get('seeds')}: "
                   f"mean **{_f(rep.get('xcity_mae_mean'))}** ± "
                   f"{_f(rep.get('xcity_mae_std'))} m")
        out.append(f"- cross-city RMSE across seeds: mean "
                   f"**{_f(rep.get('xcity_rmse_mean'))}** ± "
                   f"{_f(rep.get('xcity_rmse_std'))} m\n")

    # ---- reference points ----
    out.append("## Reference points (context, NOT targets)\n")
    out.append("- Learned monocular height on DFC2019-class data: rough **2–4 m RMSE** band.")
    out.append("- Researched shadow-based reference: **~3.84 m RMSE**.")
    out.append("- These are external context to interpret the numbers above; they are "
               "not pass/fail thresholds and were not tuned to our data.\n")

    # ---- decision ----
    out.append("## Phase-2 checkpoint decision\n")
    if dec:
        out.append(f"### Verdict: **{dec.get('verdict')}**\n")
        out.append(dec.get("summary", "") + "\n")
        crits = dec.get("criteria", [])
        if crits:
            out.append("| criterion | pass | measured | threshold | meaning |")
            out.append("|---|:--:|--:|--:|---|")
            for c in crits:
                out.append(f"| `{c['name']}` | {'✅' if c['passed'] else '❌'} | "
                           f"{_f(c['measured'], 3)} | {_f(c['threshold'], 3)} | {c['note']} |")
        out.append("\n> " + dec.get("human_note", "") + "\n")
    else:
        out.append("_No decision recorded._\n")

    # ---- what this proves ----
    out.append("## What this run does and does NOT prove\n")
    out.append("- It measures whether a **small learned RGB+depth fusion head beats "
               "trivial affine calibration on a fully held-out city**, using DFC2019 "
               "(US WorldView-3) imagery.")
    out.append("- It does **not** establish accuracy on **Indian ISRO optical imagery** "
               "(the final evaluation domain). Cross-*city* generalization within DFC2019 "
               "is a necessary-but-insufficient proxy; cross-*sensor/country* shift is the "
               "top open risk and is out of scope for Phase 1.")
    out.append("- Absolute nDSM error does **not** include DTM error; a full DSM adds "
               "terrain from a DEM, whose own error compounds. Not evaluated here.\n")

    out.append("## Reproduce\n")
    out.append("```bash\npython scripts/run_phase1.py --config configs/phase1.yaml\n```\n")
    return "\n".join(out)


def write_report(results: dict, path: str) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(render(results), encoding="utf-8")
    print(f"[report] wrote {path}")
